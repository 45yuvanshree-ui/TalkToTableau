from routing.complexity import (
    AnalyticalComplexityAnalyzer,
    infer_routing_request,
)
from routing.router import AdaptiveRouter
from routing.models import ModelTier


def test_simple_total_revenue_is_fast():
    request = infer_routing_request(
        "What is the total revenue from all sales?",
        schema_size=9,
    )

    decision = AdaptiveRouter().route(request)

    assert request.sql_complexity == 2
    assert request.reasoning_required is False
    assert decision.tier == ModelTier.FAST


def test_revenue_by_region_detects_grouping():
    request = infer_routing_request(
        "What is the total revenue generated by each region?",
        schema_size=9,
    )

    assert request.sql_complexity >= 3
    assert request.reasoning_required is False


def test_multiple_metrics_and_highest_profit_require_reasoning():
    request = infer_routing_request(
        "For each product, calculate the total revenue, total quantity sold, "
        "and profit, and identify which product generated the highest profit.",
        schema_size=9,
    )

    decision = AdaptiveRouter().route(request)

    assert request.sql_complexity >= 4
    assert request.reasoning_required is True
    assert request.output_complexity >= 3
    assert decision.tier == ModelTier.REASONING


def test_profit_margin_against_average_is_detected_as_complex():
    request = infer_routing_request(
        "Which regions have a profit margin above the overall average "
        "profit margin, and what are their total revenue and total "
        "quantity sold?",
        schema_size=9,
    )

    decision = AdaptiveRouter().route(request)

    assert request.sql_complexity >= 3
    assert request.output_complexity >= 2
    assert decision.tier != ModelTier.FAST


def test_temporal_profitability_analysis_requires_reasoning():
    request = infer_routing_request(
        "Analyze the sales data by year and region to determine which "
        "region shows the strongest improvement in profitability from "
        "2024 to 2025. Compare its revenue, cost, profit, quantity sold, "
        "and profit margin across the two years, and explain the main "
        "factors contributing to the change.",
        schema_size=9,
    )

    decision = AdaptiveRouter().route(request)

    assert request.sql_complexity >= 4
    assert request.reasoning_required is True
    assert request.output_complexity >= 4
    assert decision.tier == ModelTier.REASONING


def test_analyzer_preserves_original_request():
    question = "Show total revenue by region."

    request = AnalyticalComplexityAnalyzer.analyze(
        question,
        schema_size=12,
    )

    assert request.user_request == question
    assert request.schema_size == 12


def test_schema_size_is_at_least_one():
    request = infer_routing_request(
        "Show revenue.",
        schema_size=0,
    )

    assert request.schema_size == 1


def test_routing_does_not_depend_on_word_count():
    short = infer_routing_request(
        "Revenue?",
        schema_size=25,
    )

    long = infer_routing_request(
        "Please provide a detailed analytical explanation of the "
        "requested business performance information using the "
        "available data.",
        schema_size=5,
    )

    short_decision = AdaptiveRouter().route(short)
    long_decision = AdaptiveRouter().route(long)

    assert short_decision.complexity_score != len("Revenue?")
    assert long_decision.complexity_score != len(long.user_request)